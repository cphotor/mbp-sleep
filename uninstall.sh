#!/bin/bash
# uninstall.sh -- remove mbp-sleep from this machine and put back what it replaced.
#
# It is the exact inverse of install.sh:
#
#   * stops and disables the service, removes the unit, the sleep hook, the
#     program and the two drop-ins;
#   * restores every file that install.sh had copied aside, from the newest
#     /var/backups/mbp-sleep/<timestamp>/manifest.tsv;
#   * puts logind's own lid handling back into force, so a closed lid suspends
#     the machine again even if the desktop is not running.
#
# Nothing is deleted without being copied to /var/backups/mbp-sleep/ first.

set -uo pipefail

BIN="/usr/local/sbin/mbp-sleep"
CONF="/etc/mbp-sleep.conf"
UNIT="/etc/systemd/system/mbp-sleep.service"
HOOK="/usr/lib/systemd/system-sleep/50-mbp-sleep"
SLEEP_DROPIN="/etc/systemd/system/systemd-suspend.service.d/10-no-freeze.conf"
LID_DROPIN="/etc/systemd/logind.conf.d/50-mbp-sleep.conf"
POLICY="/etc/polkit-1/rules.d/49-mbp-sleep-no-force-suspend.rules"
STATE="/run/mbp-sleep"

info() { printf '  %s\n' "$*"; }
fail() { printf '\n  FAILED: %s\n' "$*" >&2; exit 1; }

[[ $EUID -eq 0 ]] || { command -v pkexec >/dev/null && exec pkexec "$0" "$@"; }
[[ $EUID -eq 0 ]] || fail "must run as root"

echo
echo "mbp-sleep uninstaller"
echo "---------------------"
echo

# ---------------------------------------------------------------------------
# 1. stop the service first, so nothing rewrites the files we are about to move
# ---------------------------------------------------------------------------
if systemctl list-unit-files mbp-sleep.service >/dev/null 2>&1; then
	systemctl disable --now mbp-sleep.service >/dev/null 2>&1
	info "stopped and disabled mbp-sleep.service"
fi
rm -rf "$STATE"

# ---------------------------------------------------------------------------
# 2. remove what install.sh created, backing it up first
# ---------------------------------------------------------------------------
STAMP="$(date +%Y%m%d-%H%M%S)"
BACKUP="/var/backups/mbp-sleep/uninstall-${STAMP}"
mkdir -p "$BACKUP"

keep() {
	local target="$1"
	[[ -e "$target" || -L "$target" ]] || return 0
	cp -a "$target" "${BACKUP}/$(basename "$target")"
	printf '%s\t%s\n' "$target" "$(basename "$target")" >>"${BACKUP}/manifest.tsv"
}

for file in "$UNIT" "$HOOK" "$BIN" "$SLEEP_DROPIN" "$LID_DROPIN" "$CONF"; do
	keep "$file"
	rm -f "$file"
	[[ -e "$file" ]] || info "removed $file"
done

# The polkit rule is generated by the daemon from `silence_force_prompt`, so it
# is never a file someone else wrote.  Remove it only if it carries the marker.
if [[ -e "$POLICY" ]] && grep -q 'generated by mbp-sleep' "$POLICY" 2>/dev/null; then
	rm -f "$POLICY"
	info "removed $POLICY"
fi

systemctl daemon-reload
info "reloaded systemd"

# ---------------------------------------------------------------------------
# 3. logind must stop ignoring the lid, or a closed lid does nothing at all
# ---------------------------------------------------------------------------
if [[ -e "$LID_DROPIN" ]]; then
	info "logind drop-in still present, lid handling NOT restored"
else
	systemctl kill -s HUP systemd-logind 2>/dev/null \
		&& info "logind reloaded: HandleLidSwitch is back to its default" \
		|| info "logind could not be reloaded; reboot before closing the lid"
fi

# ---------------------------------------------------------------------------
# 4. put back anything install.sh replaced
# ---------------------------------------------------------------------------
RESTORE=""
if [[ ${1:-} == "--restore" && -n ${2:-} ]]; then
	RESTORE="$2"
else
	RESTORE="$(ls -d /var/backups/mbp-sleep/[0-9]*/ 2>/dev/null | sort | tail -1)"
fi

if [[ -n "$RESTORE" && -r "${RESTORE}/manifest.tsv" ]]; then
	echo
	info "restoring from $RESTORE"
	while IFS=$'\t' read -r target name; do
		[[ -n "$target" && -n "$name" ]] || continue
		[[ -e "${RESTORE}/${name}" ]] || continue
		mkdir -p "$(dirname "$target")"
		cp -a "${RESTORE}/${name}" "$target"
		info "restored $target"
	done <"${RESTORE}/manifest.tsv"
	systemctl daemon-reload
else
	info "no earlier installation backup found; nothing to restore"
fi

# ---------------------------------------------------------------------------
# 5. verify
# ---------------------------------------------------------------------------
echo
echo "verification"
info "service   : $(systemctl is-active mbp-sleep.service 2>/dev/null || true)$( [[ -e $UNIT ]] && echo ' (unit still present)')"
info "program   : $([[ -e $BIN ]] && echo present || echo removed)"
info "hook dir  : $(ls /usr/lib/systemd/system-sleep/ 2>/dev/null | tr '\n' ' ')"
info "lid file  : $([[ -e $LID_DROPIN ]] && echo present || echo removed)"
info "freeze    : $([[ -e $SLEEP_DROPIN ]] && echo present || echo removed)"
echo
echo "backups from this run: $BACKUP"
if [[ -d /var/backups/mbp-sleep ]]; then
	echo "all backups:"
	ls -1 /var/backups/mbp-sleep
fi
echo
echo "Result: the machine is back to logind's own suspend handling and the"
echo "systemd-sleep hooks that existed before mbp-sleep was installed."
echo
